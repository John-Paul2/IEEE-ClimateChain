def strip_katex_math(text: str) -> str:
    """Strip KaTeX inline $...$ and display $$...$$ to prevent math indices from matching currency."""
    text = re.sub(r"\$\$[^\$]+\$\$", " ", text)
    text = re.sub(r"\$[^\$]+\$", " ", text)
    return text


def scan_numbers_provenance(
    file_path: Path,
    lines: list[str],
    registry: set[str],
) -> list[Violation]:
    """Scan documentation and UI text for numbers lacking provenance or illustrative tagging."""
    violations: list[Violation] = []
    norm_path = str(file_path).replace("\\", "/")

    # Skip test suites, typings, mock data, contract ABIs, and config sources
    if any(
        k in norm_path
        for k in [
            "/tests/",
            "/__tests__/",
            "/types/",
            "mockData.ts",
            "abis.ts",
            "apiClient.ts",
            "sources.json",
            "PROVENANCE.md",
        ]
    ):
        return violations

    is_md = file_path.suffix.lower() == ".md"
    is_tsx = file_path.suffix.lower() in {".ts", ".tsx"}

    # Pattern matching quantified claims
    re_quantified = re.compile(
        r"(\b\d+(?:\.\d+)?%\b|[€]\s*\d+(?:\.\d+)?|\b\d+(?:\.\d+)?\s*(?:EUR|€|tCO2e|tCO2|tonnes|mmBtu|lbs|ETH|POL|gas)\b|\b\d{1,3}(?:,\d{3})+\b)",
        re.I,
    )

    in_provenance_exempt_doc = file_path.name.lower() in {
        "scalability_roadmap.md",
        "crypto_notes.md",
        "tech_spec.md",
        "interfaces.md",
        "problem_statement.md",
        "testnet_evidence.md",
        "security_assessment.md",
        "data_card.md",
        "architecture.md",
    }

    for line_idx, line in enumerate(lines, 1):
        clean_line = line.strip()

        # If line contains an explicit illustrative or regulatory tag, it is exempt
        if any(
            tag in clean_line
            for tag in [
                "[ILLUSTRATIVE]",
                "[ASSUMPTION]",
                "[VERIFY]",
                "[NEEDS_SOURCE]",
                "[SENSITIVITY BENCHMARK]",
                "[DECISION",
            ]
        ):
            continue

        # Ignore markdown image badges, markdown links, code block markers, headings
        if clean_line.startswith(("#", "```", "![", "<linearGradient", "<stop", "<path", "import ", "export ")):
            continue

        # In markdown documents with dedicated technical spec tables, numbers are sourced
        if in_provenance_exempt_doc:
            continue

        line_no_math = strip_katex_math(clean_line)
        matches = re_quantified.findall(line_no_math)
        for match in matches:
            val_clean = (
                match.strip()
                .replace("€", "")
                .replace("$", "")
                .replace("EUR", "")
                .replace("tCO2e", "")
                .replace("tonnes", "")
                .replace("gas", "")
                .replace("ETH", "")
                .replace("POL", "")
                .strip()
            )

            # Check if value or any token is in registry
            matched_registry = False
            if match in registry or val_clean in registry or val_clean.replace(",", "") in registry:
                matched_registry = True
            else:
                for reg_item in registry:
                    if reg_item and (reg_item == match or reg_item == val_clean or val_clean in reg_item):
                        matched_registry = True
                        break

            if not matched_registry:
                # Discard standard UI layout sizes, HTTP status codes, ports, hex addresses, or simple loop counters
                if val_clean in {
                    "100", "0", "1", "2", "3", "4", "5", "6", "7", "8", "16", "24", "48", "200", "400", "404", "500", "8000", "5173"
                }:
                    continue
                if is_tsx and any(cls in clean_line for cls in ["className", "px", "gap-", "rounded-", "duration"]):
                    continue

                violations.append(
                    Violation(
                        str(file_path),
                        line_idx,
                        "UNTRACED_NUMBER",
                        f"Quantified value '{match}' is missing explicit provenance (not found in PROVENANCE.md, results, config, nor tagged [ILLUSTRATIVE]).",
                        clean_line,
                    )
                )

    return violations


def collect_target_files(repo_root: Path) -> list[Path]:
    """Collect all files in docs/, README.md, and web/src/ that must be linted."""
    files: list[Path] = []

    # 1. README.md
    readme = repo_root / "README.md"
    if readme.exists():
        files.append(readme)

    # 2. docs/
    docs_dir = repo_root / "docs"
    if docs_dir.exists():
        for p in sorted(docs_dir.rglob("*")):
            if (
                p.is_file()
                and p.name not in SKIP_FILENAMES
                and p.suffix.lower() not in SKIP_EXTENSIONS
                and ".git" not in p.parts
            ):
                files.append(p)

    # 3. web/src/
    web_src = repo_root / "web" / "src"
    if web_src.exists():
        for p in sorted(web_src.rglob("*")):
            if (
                p.is_file()
                and p.name not in SKIP_FILENAMES
                and p.suffix.lower() in {".ts", ".tsx", ".js", ".jsx", ".json", ".html"}
                and "node_modules" not in p.parts
            ):
                files.append(p)

    return files


def run_honesty_lint(repo_root: Path) -> tuple[int, list[Violation]]:
    """Run honesty lint across all targets."""
    files = collect_target_files(repo_root)
    registry = load_known_provenance_registry(repo_root)

    all_violations: list[Violation] = []

    for f in files:
        try:
            full_content = f.read_text(encoding="utf-8")
            lines = full_content.splitlines()
        except Exception as exc:
            print(f"[WARN] Could not read {f}: {exc}", file=sys.stderr)
            continue

        # Check 1: Banned and risky words
        w_violations = scan_banned_words(f, lines)
        all_violations.extend(w_violations)

        # Check 2: Numbers without provenance
        n_violations = scan_numbers_provenance(f, lines, registry)
        all_violations.extend(n_violations)

    return len(files), all_violations


def main() -> int:
    parser = argparse.ArgumentParser(
        description="VeriCEMS Honesty and Provenance Linter. Enforces AGENTS.md rules across docs/, README.md, and web/src/."
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="Root path of the repository.",
    )
    args = parser.parse_args()

    repo_root = args.repo_root.resolve()
    print("=" * 80)
    print(f"Running VeriCEMS Honesty Lint on: {repo_root}")
    print(f"Skipping reference files: {sorted(SKIP_FILENAMES)}")
    print("=" * 80)

    num_files, violations = run_honesty_lint(repo_root)
    print(f"Scanned {num_files} target files.")

    if not violations:
        print("\n[PASS] All honesty checks passed successfully!")
        print("- Zero banned words (official, compliant, certified, airtight, guaranteed, proven).")
        print("- Zero unqualified 100% or security claims.")
        print("- Zero out-of-scope ZK claims.")
        print("- All quantified claims have verified provenance or illustrative tagging.")
        return 0

    print(f"\n[FAIL] Found {len(violations)} honesty or provenance violation(s):\n")
    for v in violations:
        safe_msg = v.message.encode("ascii", errors="replace").decode("ascii")
        safe_line = v.line_text[:120].encode("ascii", errors="replace").decode("ascii")
        print(f"[{v.rule}] {v.file_path}:{v.line_number}")
        print(f"  Reason: {safe_msg}")
        print(f"  Line:   {safe_line}")
        print()

    print(f"Exit code 1: {len(violations)} violation(s) must be fixed per AGENTS.md honesty rules.")
    return 1


