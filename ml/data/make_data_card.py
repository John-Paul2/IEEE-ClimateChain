"""Automatically generate `docs/DATA_CARD.md` from inspection and pipeline outputs (Milestone P03, Task 8).

Reads:
- `results/data_inspection.json` (generated by `ml/data/inspect.py`)
- `data/processed/preprocessing_manifest.json` (generated by `ml/data/preprocess.py`)
- `results/splits.json` (generated by `ml/data/splits.py`)
- `config/facilities.yaml`
- `config/emission_factors.yaml`
- `schemas/channels.json`

Writes:
- `docs/DATA_CARD.md` with zero hand-edited or invented numbers.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from ml.data.yaml_loader import load_yaml_file

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_INSPECTION_PATH = REPO_ROOT / "results" / "data_inspection.json"
DEFAULT_PREPROCESS_MANIFEST_PATH = REPO_ROOT / "data" / "processed" / "preprocessing_manifest.json"
DEFAULT_SPLITS_PATH = REPO_ROOT / "results" / "splits.json"
DEFAULT_FACILITIES_CONFIG_PATH = REPO_ROOT / "config" / "facilities.yaml"
DEFAULT_EMISSION_FACTORS_PATH = REPO_ROOT / "config" / "emission_factors.yaml"
DEFAULT_CHANNELS_PATH = REPO_ROOT / "schemas" / "channels.json"
DEFAULT_OUTPUT_DOC_PATH = REPO_ROOT / "docs" / "DATA_CARD.md"


def _fmt_range(col_entry: dict[str, Any]) -> str:
    vr = col_entry["value_range"]
    if col_entry["inferred_type"] in ("integer", "float"):
        return (
            f"min={vr['min']}, p05={vr['p05']}, median={vr['median']}, "
            f"mean={vr['mean']}, p95={vr['p95']}, max={vr['max']}"
        )
    return (
        f"distinct={vr.get('distinct_count')}, "
        f"range=[{vr.get('min_lex')} .. {vr.get('max_lex')}]"
    )


def render_data_card_markdown(
    inspection: dict[str, Any],
    preprocess_manifest: dict[str, Any],
    splits_manifest: dict[str, Any],
    facilities_config: dict[str, Any],
    emission_factors_config: dict[str, Any],
    channels_registry: dict[str, Any],
) -> str:
    """Render `docs/DATA_CARD.md` markdown deterministically from structured artifacts."""
    ds = inspection["dataset_summary"]
    ps = preprocess_manifest["summary"]
    missing_chk = inspection["missing_physical_channels_check"]
    circ = inspection["co2_heat_input_circularity"]

    lines: list[str] = []
    lines.append("# VeriCEMS Dataset Card (`DATA_CARD.md`)")
    lines.append("")
    lines.append(
        "> **Generated automatically by:** [`ml/data/make_data_card.py`](file:///c:/Users/LENOVO/Documents/Hackathons/IEEE%20Climate%20Change/ml/data/make_data_card.py) "
        "from [`results/data_inspection.json`](file:///c:/Users/LENOVO/Documents/Hackathons/IEEE%20Climate%20Change/results/data_inspection.json), "
        "[`data/processed/preprocessing_manifest.json`](file:///c:/Users/LENOVO/Documents/Hackathons/IEEE%20Climate%20Change/data/processed/preprocessing_manifest.json), and "
        "[`results/splits.json`](file:///c:/Users/LENOVO/Documents/Hackathons/IEEE%20Climate%20Change/results/splits.json)."
    )
    lines.append(
        "> **Core Framing Statement:** This dataset is a **US power-sector proxy for industrial installations** covered by EU CBAM."
    )
    lines.append("")
    lines.append("---")
    lines.append("")

    # 1. Source, Licence, and Proxy Framing
    lines.append("## 1. Source, Licence, and Proxy Framing")
    lines.append("")
    lines.append(
        "- **Official Source:** United States Environmental Protection Agency (US EPA), "
        "Clean Air Markets Program Data (CAMPD) / Emissions Collection and Monitoring Plan System (ECMPS), "
        "reported under **40 CFR Part 75**."
    )
    lines.append(
        f"- **Portal & Bulk Endpoint:** `{facilities_config.get('source_portal_url')}` "
        f"(`{facilities_config.get('bulk_files_base_url')}/emissions/hourly/state/emissions-hourly-{facilities_config.get('calendar_year')}-<state>.csv`)."
    )
    lines.append(
        "- **Licence & Public-Domain Status:** Official U.S. Government work (17 U.S.C. § 105), "
        "in the public domain worldwide and free to use, redistribute, and analyze without restriction."
    )
    lines.append(
        "- **Industrial Proxy Statement:** This dataset represents a **US power-sector proxy for industrial installations** "
        "(such as steel, cement, aluminium, and fertiliser plants subject to EU CBAM). We use US EPA Part 75 "
        "power-plant Continuous Emission Monitoring System (CEMS) records because they provide a large, public, "
        "real-world hourly record of combustion load swings, startups, shutdowns, and analyzer noise. "
        "However, power-plant boilers and turbines do not directly include non-combustion process emissions "
        "(e.g., limestone calcination in clinker production or blast-furnace reduction)."
    )
    lines.append("")

    # 2. Facilities, States, Calendar Year, and Row Counts
    lines.append("## 2. Facilities, Calendar Year, and Dataset Scale")
    lines.append("")
    lines.append(
        f"- **Calendar Year Used:** `{', '.join(ds['calendar_years'])}` "
        f"(full calendar year `{ds['date_min']}` through `{ds['date_max']}`, hours `0..23`)."
    )
    lines.append(f"- **States Downloaded:** `{', '.join(ds['states'])}` (`{', '.join(inspection['source_files'])}`).")
    lines.append(
        f"- **Selection Rule (`config/facilities.yaml`):** {facilities_config.get('selection_rule')}"
    )
    lines.append(f"- **Raw Facilities Downloaded:** `{ds['facilities_count']}` facilities (`{ds['units_count']}` units, `{ds['total_rows']:,}` total hourly rows).")
    lines.append(
        f"- **Raw Operating Rows (`Operating Time > 0`):** `{ds['operating_rows']:,}` rows "
        f"(overall operating-hour fraction = `{ds['operating_hour_fraction']:.4f}`, "
        f"mean operating time across operating hours = `{ds['mean_operating_time_when_operating']:.4f}`)."
    )
    lines.append(
        f"- **Preprocessed Dataset (`data/processed/`):** `{ps['processed_rows']:,}` operating rows across "
        f"`{ps['facilities_count']}` facilities and `{ps['units_count']}` unit time series Parquet files "
        f"(after removing `{ps['dropped_non_operating_rows']:,}` offline hours and `{ps['dropped_missing_core_rows']:,}` "
        "operating hours where `CO2 Mass (short tons)` or `Heat Input (mmBtu)` was missing in raw Part 75 reporting, "
        "such as NOx-only peaking turbines like Facility `8029` Sycamore Combustion Turbine)."
    )
    lines.append("")

    lines.append("### 2.1 Facilities Table (`30` Raw / `29` Preprocessed with Complete CO₂ + Heat Input)")
    lines.append("")
    lines.append(
        "| Facility ID | Facility Name | State | Units | Primary Fuels | Total Rows | Operating Rows | Operating Hour Fraction |"
    )
    lines.append("|---:|---|---|---:|---|---:|---:|---:|")
    for fac in inspection["facilities"]:
        fuels_str = ", ".join(fac["primary_fuels"])
        lines.append(
            f"| `{fac['facility_id']}` | {fac['facility_name']} | `{fac['state']}` | "
            f"{fac['units_count']} | {fuels_str} | {fac['total_rows']:,} | "
            f"{fac['operating_rows']:,} | `{fac['operating_hour_fraction']:.4f}` |"
        )
    lines.append("")

    # 3. Unit Types & Fuel Types
    lines.append("## 3. Unit Types, Fuel Types, and Operating-Hour Fractions")
    lines.append("")
    lines.append("### 3.1 Primary Fuel Types")
    lines.append("")
    lines.append("| Primary Fuel Type | Facilities | Units | Total Rows | Operating Rows | Operating Hour Fraction |")
    lines.append("|---|---:|---:|---:|---:|---:|")
    for ft in inspection["primary_fuel_types"]:
        lines.append(
            f"| `{ft['primary_fuel_type']}` | {ft['facilities_count']} | {ft['units_count']} | "
            f"{ft['total_rows']:,} | {ft['operating_rows']:,} | `{ft['operating_hour_fraction']:.4f}` |"
        )
    lines.append("")

    lines.append("### 3.2 Unit Types")
    lines.append("")
    lines.append("| Unit Type | Facilities | Units | Total Rows | Operating Rows | Operating Hour Fraction |")
    lines.append("|---|---:|---:|---:|---:|---:|")
    for ut in inspection["unit_types"]:
        lines.append(
            f"| `{ut['unit_type']}` | {ut['facilities_count']} | {ut['units_count']} | "
            f"{ut['total_rows']:,} | {ut['operating_rows']:,} | `{ut['operating_hour_fraction']:.4f}` |"
        )
    lines.append("")

    # 4. Columns Found in Real EPA CAMPD Hourly Files
    lines.append(f"## 4. Columns Found in Real EPA CAMPD Hourly Files (`{inspection['columns_count']}` Columns)")
    lines.append("")
    lines.append(
        "| # | Exact CAMPD Column Name | Pandas Dtype | Type | Documented Unit | Missing Rate (All Rows) | Missing Rate (Operating Hours) | Value Range / Summary |"
    )
    lines.append("|---:|---|---|---|---|---:|---:|---|")
    for idx, col in enumerate(inspection["columns"], start=1):
        unit_str = f"`{col['documented_unit']}`" if col["documented_unit"] else "—"
        lines.append(
            f"| {idx} | `{col['column_name']}` | `{col['pandas_dtype']}` | `{col['inferred_type']}` | "
            f"{unit_str} | `{col['missing_rate_all']:.4f}` | `{col['missing_rate_operating']:.4f}` | "
            f"{_fmt_range(col)} |"
        )
    lines.append("")

    # 5. Missing Physical Columns Check (Task 4)
    lines.append("## 5. Columns Missing from Hourly CAMPD Bulk Files (O₂, Flue Temperature, Flow Rate)")
    lines.append("")
    lines.append(
        "We programmatically inspected all column headers of the downloaded EPA CAMPD hourly CSVs "
        "for stack oxygen concentration (`O2`), flue-gas temperature, and stack volumetric flow rate:"
    )
    lines.append("")
    lines.append(f"- **Stack O₂ Concentration column present:** `{missing_chk['stack_o2_present']}` (matches: `{missing_chk['stack_o2_matching_columns']}`)")
    lines.append(f"- **Flue-Gas Temperature column present:** `{missing_chk['flue_temperature_present']}` (matches: `{missing_chk['flue_temperature_matching_columns']}`)")
    lines.append(f"- **Stack Volumetric Flow Rate column present:** `{missing_chk['stack_flow_rate_present']}` (matches: `{missing_chk['stack_flow_rate_matching_columns']}`)")
    lines.append(f"- **Missing Physical Channels:** `{', '.join(missing_chk['missing_channels'])}`")
    lines.append("")
    lines.append(f"> **Finding:** {missing_chk['finding']}")
    lines.append("")

    # 6. Derived-Field Detection & Circularity Caveat (Task 5)
    lines.append("## 6. Derived-Field Detection and the CO₂-vs-Heat-Input Circularity Caveat")
    lines.append("")
    lines.append("### 6.1 How Derived Fields Were Detected")
    lines.append("")
    lines.append(
        "To test whether `CO2 Mass (short tons)` in EPA CAMPD is independently measured or mathematically "
        "derived from `Heat Input (mmBtu)`, we ran three quantitative checks across all operating hours "
        "(`Operating Time > 0` and `Heat Input (mmBtu) > 0`) per fuel type:"
    )
    lines.append(
        "1. **Pearson Correlation ($r$ and $R^2$):** Computed linear correlation between hourly "
        "`CO2 Mass (short tons)` and `Heat Input (mmBtu)` within each fuel type."
    )
    lines.append(
        "2. **Stoichiometric Ratio Distribution ($\\text{CO}_2 / \\text{Heat Input}$):** Computed the mean, "
        "standard deviation, coefficient of variation ($\\text{CV}$), percentiles, and the fraction of operating "
        "hours where a unit's hourly ratio `round(CO2 Mass / Heat Input, 4)` equals that unit's modal constant "
        "within $\\pm 0.0002\\text{ short tons/mmBtu}$."
    )
    lines.append(
        "3. **Part 75 Measure Indicator Audit:** Cross-tabulated `CO2 Mass Measure Indicator` against "
        "`Heat Input Measure Indicator` and compared empirical ratios against the unverified reference "
        "factors recorded in [`config/emission_factors.yaml`](file:///c:/Users/LENOVO/Documents/Hackathons/IEEE%20Climate%20Change/config/emission_factors.yaml)."
    )
    lines.append("")

    lines.append("### 6.2 Empirical Ratio and Correlation Results by Fuel Type")
    lines.append("")
    lines.append(
        "| Primary Fuel Type | Operating Hours ($n$) | Pearson $r$ | $R^2$ | Mean Ratio (`short_tons/mmBtu`) | Std Ratio | CV (%) | Median Ratio | 5th–95th Percentile | Within-Unit Constant Ratio Fraction | Circular? |"
    )
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|---|---:|---|")
    for fuel_name, fstats in circ["per_fuel_type"].items():
        r_obj = fstats["ratio_short_tons_co2_per_mmbtu"]
        lines.append(
            f"| `{fuel_name}` | {fstats['operating_hours_evaluated']:,} | `{fstats['pearson_r']:.6f}` | "
            f"`{fstats['r_squared']:.6f}` | `{r_obj['mean']:.6f}` | `{r_obj['std']:.6f}` | "
            f"`{r_obj['cv_pct']:.2f}%` | `{r_obj['median']:.6f}` | "
            f"`[{r_obj['p05']:.6f}, {r_obj['p95']:.6f}]` | "
            f"`{fstats['within_unit_constant_ratio_fraction']:.4f}` | `{fstats['is_circular']}` |"
        )
    lines.append("")

    lines.append("### 6.3 The Circularity Caveat")
    lines.append("")
    lines.append(f"**Overall Circularity Finding (`is_circular = {circ['is_circular']}`):**")
    lines.append("")
    lines.append(circ["circularity_finding"])
    lines.append("")
    lines.append(
        "- **Note on Published Emission Factors (`config/emission_factors.yaml`):** "
        "All published reference factors cited in [`config/emission_factors.yaml`](file:///c:/Users/LENOVO/Documents/Hackathons/IEEE%20Climate%20Change/config/emission_factors.yaml) "
        "carry their official EPA URLs and are marked `status: \"unverified\"` until confirmed by human review. "
        "VeriCEMS detectors never hardcode emission factors; empirical ratios are estimated solely from training-split facilities."
    )
    lines.append("")

    # 7. Preprocessing & Facility-Grouped Splits
    lines.append("## 7. Preprocessing Rules and Facility-Grouped Splits (`GroupShuffleSplit`)")
    lines.append("")
    lines.append("### 7.1 Preprocessing Rules (`ml/data/preprocess.py`)")
    lines.append(
        f"- **Operating Hours Retained:** Only rows with `Operating Time > 0` are retained (`{ps['operating_raw_rows']:,}` of `{ps['total_raw_rows']:,}` raw rows)."
    )
    lines.append(
        f"- **Short-Gap Interpolation:** Isolated gaps up to `{preprocess_manifest['rules']['max_interp_gap_hours']}` "
        "consecutive operating hours within a unit time series are linearly interpolated (`limit=3`, forward direction)."
    )
    lines.append(
        f"- **Core Channel Integrity:** Operating rows where `heat_input_mmbtu` or `co2_mass_short_tons` remains missing "
        f"or non-positive after short-gap interpolation are dropped (`{ps['dropped_missing_core_rows']:,}` rows dropped)."
    )
    lines.append(
        "- **Auxiliary Channels:** Remaining `NaN` values in `gross_load_mw`, `steam_load_1000_lb_hr`, `so2_mass_lbs`, "
        "and `nox_mass_lbs` are zero-filled after recording boolean missingness flags (`gross_load_missing_flag`, `steam_load_missing_flag`)."
    )
    lines.append(
        f"- **One Time Series Per Unit:** Saved `{ps['units_count']}` individual unit Parquet files under `data/processed/units/` "
        f"plus `{ps['combined_parquet']}` (`{ps['processed_rows']:,}` total processed rows)."
    )
    lines.append("")

    lines.append("### 7.2 Facility-Grouped Splits (`results/splits.json`)")
    lines.append("")
    lines.append(
        f"- **Splitter:** `{splits_manifest['splitter']}` across `{splits_manifest['n_facilities']}` facilities "
        f"(`{splits_manifest['n_splits']}` repeated random splits, fixed `base_seed = {splits_manifest['base_seed']}`)."
    )
    lines.append("- **Zero Facility Leakage:** Every split partitions facility IDs into strictly disjoint `train`, `val`, and `test` sets.")
    lines.append("")
    lines.append("| Split Index | Seed | Train Facilities (`n`) | Val Facilities (`n`) | Test Facilities (`n`) | Test Facility IDs |")
    lines.append("|---:|---:|---:|---:|---:|---|")
    for sp in splits_manifest["splits"]:
        test_ids_str = ", ".join(f"`{fid}`" for fid in sp["test_facility_ids"])
        lines.append(
            f"| `{sp['split_index']}` | `{sp['seed']}` | {len(sp['train_facility_ids'])} | "
            f"{len(sp['val_facility_ids'])} | {len(sp['test_facility_ids'])} | {test_ids_str} |"
        )
    lines.append("")

    # 8. Channel Registry Table (Real vs. Synthetic)
    lines.append("## 8. Telemetry Channels Table (`schemas/channels.json` — Real vs. Synthetic)")
    lines.append("")
    lines.append(
        "| Channel Name | Unit | Source (`real` / `synthetic`) | Status | Exact CAMPD Column | Derived in Part 75? | Description |"
    )
    lines.append("|---|---|---|---|---|---|---|")
    for ch in channels_registry["channels"]:
        campd_col = f"`{ch['campd_column']}`" if ch.get("campd_column") else "— *(synthetic)*"
        derived_flag = "`true`" if ch.get("derived_in_part75") else "`false`"
        lines.append(
            f"| `{ch['name']}` | `{ch['unit']}` | **`{ch['source']}`** | `{ch['status']}` | "
            f"{campd_col} | {derived_flag} | {ch['description']} |"
        )
    lines.append("")

    return "\n".join(lines)


def generate_data_card(
    inspection_path: Path = DEFAULT_INSPECTION_PATH,
    preprocess_manifest_path: Path = DEFAULT_PREPROCESS_MANIFEST_PATH,
    splits_path: Path = DEFAULT_SPLITS_PATH,
    facilities_config_path: Path = DEFAULT_FACILITIES_CONFIG_PATH,
    emission_factors_path: Path = DEFAULT_EMISSION_FACTORS_PATH,
    channels_path: Path = DEFAULT_CHANNELS_PATH,
    output_doc_path: Path = DEFAULT_OUTPUT_DOC_PATH,
) -> Path:
    """Load all inspection/preprocessing/split artifacts and write `docs/DATA_CARD.md`."""
    inspection = json.loads(inspection_path.read_text(encoding="utf-8"))
    preprocess_manifest = json.loads(preprocess_manifest_path.read_text(encoding="utf-8"))
    splits_manifest = json.loads(splits_path.read_text(encoding="utf-8"))
    facilities_config = load_yaml_file(facilities_config_path)
    emission_factors_config = load_yaml_file(emission_factors_path)
    channels_registry = json.loads(channels_path.read_text(encoding="utf-8"))

    md = render_data_card_markdown(
        inspection=inspection,
        preprocess_manifest=preprocess_manifest,
        splits_manifest=splits_manifest,
        facilities_config=facilities_config,
        emission_factors_config=emission_factors_config,
        channels_registry=channels_registry,
    )
    output_doc_path.parent.mkdir(parents=True, exist_ok=True)
    output_doc_path.write_text(md, encoding="utf-8")
    return output_doc_path


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate docs/DATA_CARD.md from real CAMPD inspection and preprocessing outputs."
    )
    parser.add_argument("--inspection", type=Path, default=DEFAULT_INSPECTION_PATH)
    parser.add_argument(
        "--preprocess-manifest", type=Path, default=DEFAULT_PREPROCESS_MANIFEST_PATH
    )
    parser.add_argument("--splits", type=Path, default=DEFAULT_SPLITS_PATH)
    parser.add_argument("--facilities", type=Path, default=DEFAULT_FACILITIES_CONFIG_PATH)
    parser.add_argument(
        "--emission-factors", type=Path, default=DEFAULT_EMISSION_FACTORS_PATH
    )
    parser.add_argument("--channels", type=Path, default=DEFAULT_CHANNELS_PATH)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_DOC_PATH)
    args = parser.parse_args()

    out = generate_data_card(
        inspection_path=args.inspection,
        preprocess_manifest_path=args.preprocess_manifest,
        splits_path=args.splits,
        facilities_config_path=args.facilities,
        emission_factors_path=args.emission_factors,
        channels_path=args.channels,
        output_doc_path=args.output,
    )
    print(f"Generated {out} ({out.stat().st_size} bytes).")


if __name__ == "__main__":
    main()
